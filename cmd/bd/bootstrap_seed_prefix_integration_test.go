// writeUnprovisionedServerWorkspace writes dir/.beads for a server-mode workspace on
// the test Dolt server, the way a provisioner that never ran bd init leaves
// it: metadata.json names the server and database but carries no project_id,
// there is no local shadow directory, and config.yaml names the issue prefix
// and turns off auto-start.
func writeUnprovisionedServerWorkspace(t *testing.T, dir, database string, port int) string {
	t.Helper()
	beadsDir := filepath.Join(dir, ".beads")
	if err := os.MkdirAll(beadsDir, 0o700); err != nil {
		t.Fatal(err)
	}
	meta := fmt.Sprintf(`{"backend":"dolt","database":"dolt","dolt_mode":"server","dolt_server_host":"127.0.0.1","dolt_server_port":%d,"dolt_database":%q}`, port, database)
	if err := os.WriteFile(filepath.Join(beadsDir, "metadata.json"), []byte(meta), 0o644); err != nil {
		t.Fatal(err)
	}
	yaml := "issue-prefix: la\ndolt:\n  auto-start: false\n"
	if err := os.WriteFile(filepath.Join(beadsDir, "config.yaml"), []byte(yaml), 0o644); err != nil {
		t.Fatal(err)
	}
	return beadsDir
}

// testServerSQL runs fn against the test Dolt server with no database
// selected.
func testServerSQL(t *testing.T, fn func(ctx context.Context, db *sql.DB) error) {
	t.Helper()
	db, err := sql.Open("mysql", doltutil.ServerDSN{Host: "127.0.0.1", Port: testDoltServerPort, User: "root"}.String())
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	if err := fn(ctx, db); err != nil {
		t.Fatal(err)
	}
}

// serverIssuePrefix returns database's issue_prefix row on the test server,
// or "" when it has none.
func serverIssuePrefix(t *testing.T, database string) (string, error) {
	t.Helper()
	var value string
	var queryErr error
	testServerSQL(t, func(ctx context.Context, db *sql.DB) error {
		//nolint:gosec // G201: database is generated by uniqueTestDBName
		queryErr = db.QueryRowContext(ctx, fmt.Sprintf("SELECT value FROM `%s`.config WHERE `key` = 'issue_prefix'", database)).Scan(&value)
		if queryErr == sql.ErrNoRows {
			queryErr = nil
		}
		return nil
	})
	return value, queryErr
}

// createServerDatabaseWithoutPrefix creates database on the test server with
// the full Beads schema and no issue_prefix row, from a scratch directory so
// the workspace under test gains no local state. A database with the schema
// is a candidate in bootstrap's metadata reconcile, which therefore cannot
// redirect the workspace to the server's only other Beads database.
func createServerDatabaseWithoutPrefix(t *testing.T, database string) {
	t.Helper()
	scratch := filepath.Join(t.TempDir(), ".beads")
	store, err := dolt.New(context.Background(), &dolt.Config{
		Path:            filepath.Join(scratch, "dolt"),
		BeadsDir:        scratch,
		ServerHost:      "127.0.0.1",
		ServerPort:      testDoltServerPort,
		Database:        database,
		CreateIfMissing: true,
	})
	if err != nil {
		t.Fatalf("create server database %s: %v", database, err)
	}
	if err := store.Close(); err != nil {
		t.Fatalf("close store: %v", err)
	}
	if got, err := serverIssuePrefix(t, database); err != nil || got != "" {
		t.Fatalf("fixture database issue_prefix = %q (err %v), want no row", got, err)
	}
}

func bootstrapServerTestEnv() []string {
	return append(os.Environ(), "BD_DISABLE_METRICS=1", "DO_NOT_TRACK=1")
}

// AC-4: jsonl-import into a server database whose issue_prefix is already
// "xx" keeps it, even though config.yaml names "la", and imports the issue
// under its own ID. The action used to overwrite the prefix unconditionally.
func TestCLI_Bootstrap_JSONLImportKeepsExistingServerPrefix_E2E(t *testing.T) {
	skipIfNoDolt(t)

	dir := t.TempDir()
	database := uniqueTestDBName(t)
	t.Cleanup(func() { dropTestDatabase(database, testDoltServerPort) })
	createServerDatabaseWithoutPrefix(t, database)
	testServerSQL(t, func(ctx context.Context, db *sql.DB) error {
		//nolint:gosec // G201: database is generated by uniqueTestDBName
		_, err := db.ExecContext(ctx, fmt.Sprintf("INSERT INTO `%s`.config (`key`, `value`) VALUES ('issue_prefix', 'xx')", database))
		return err
	})
	beadsDir := writeUnprovisionedServerWorkspace(t, dir, database, testDoltServerPort)
	jsonl := `{"id":"la-1","title":"imported","status":"open","priority":2,"issue_type":"task","created_at":"2026-01-01T00:00:00Z","updated_at":"2026-01-01T00:00:00Z"}` + "\n"
	if err := os.WriteFile(filepath.Join(beadsDir, "issues.jsonl"), []byte(jsonl), 0o644); err != nil {
		t.Fatal(err)
	}

	stdout, stderr, err := runBDExecSeparated(t, testBD, dir, bootstrapServerTestEnv(), "bootstrap", "--yes")
	if err != nil {
		t.Fatalf("bd bootstrap --yes: %v\nstdout:\n%s\nstderr:\n%s", err, stdout, stderr)
	}
	if !strings.Contains(stdout, "Bootstrap plan: import from git-tracked JSONL") {
		t.Fatalf("bootstrap did not plan jsonl-import:\nstdout:\n%s\nstderr:\n%s", stdout, stderr)
	}
	if want := `issue_prefix already set to "xx"; left unchanged`; !strings.Contains(stderr, want) {
		t.Errorf("bootstrap stderr lacks %q:\n%s", want, stderr)
	}
	if got, err := serverIssuePrefix(t, database); err != nil || got != "xx" {
		t.Errorf("server database issue_prefix = %q (err %v), want %q", got, err, "xx")
	}
	var ids []string
	testServerSQL(t, func(ctx context.Context, db *sql.DB) error {
		//nolint:gosec // G201: database is generated by uniqueTestDBName
		rows, err := db.QueryContext(ctx, fmt.Sprintf("SELECT id FROM `%s`.issues ORDER BY id", database))
		if err != nil {
			return err
		}
		defer rows.Close()
		for rows.Next() {
			var id string
			if err := rows.Scan(&id); err != nil {
				return err
			}
			ids = append(ids, id)
		}
		return rows.Err()
	})
	if strings.Join(ids, ",") != "la-1" {
		t.Errorf("issues on the server = %v, want [la-1]", ids)
	}
}
